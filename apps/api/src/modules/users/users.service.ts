import { prisma } from "../../config/prisma";
import type { ListUsersInput } from "./users.schemas";

interface ListUsersParams extends ListUsersInput {
  currentUserId: string;
}

export async function listUsers({
  currentUserId,
  q,
  page,
  limit,
}: ListUsersParams) {
  const where = {
    id: {
      not: currentUserId,
    },
    ...(q
      ? {
          OR: [
            {
              name: {
                contains: q,
                mode: "insensitive" as const,
              },
            },
            {
              email: {
                contains: q,
                mode: "insensitive" as const,
              },
            },
          ],
        }
      : {}),
  };

  const [users, total] = await prisma.$transaction([
    prisma.user.findMany({
      where,
      select: {
        id: true,
        name: true,
        email: true,
        createdAt: true,
      },
      orderBy: {
        name: "asc",
      },
      skip: (page - 1) * limit,
      take: limit,
    }),
    prisma.user.count({ where }),
  ]);

  return {
    users,
    pagination: {
      page,
      limit,
      total,
      totalPages: Math.ceil(total / limit),
    },
  };
}
